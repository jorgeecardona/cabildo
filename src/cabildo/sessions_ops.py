"""Operations on Claude Code sessions: tag, list, export, combine, trash (#44).

The CLI, the workspace app and the MCP tools all call these functions. A session is
addressed by any id of its conversation (a chain of transcripts joined by
``continued-in``); tags live in the workspace sidecar under the chain's meta key.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import time
import uuid
from collections.abc import Iterable
from dataclasses import dataclass, replace
from pathlib import Path

from .workspace import sessions as ws

# Text Claude Code injects into the user turn. Searching or exporting it would match
# every session, so it is cut before anything else looks at a message.
_INJECTED_BLOCK = re.compile(
    r"<(system-reminder|local-command-stdout|local-command-stderr|command-name|command-message"
    r"|command-args|ide_opened_file|ide_selection|user-prompt-submit-hook|task-notification"
    r"|bash-input|bash-stdout|bash-stderr)>.*?</\1>",
    re.DOTALL,
)
_INJECTED_START = (
    "Caveat: The messages below were generated by the user",
    "[Request interrupted",
    "This session is being continued from a previous conversation",
    "[Artifact comment sent to Claude]",
)
_IMAGE_REF = re.compile(r"\[Image #\d+\]")
FIRST_TEXT_CHARS = 400


class SessionsError(ValueError):
    """An operation was refused: unknown id, nothing selected, or an unsafe trash."""


@dataclass(frozen=True)
class Turn:
    """One message of a conversation, as exported."""

    role: str  # "user" or "assistant"
    text: str
    timestamp: str


@dataclass(frozen=True)
class Combined:
    """A combined session prepared from an export; it exists once ``command`` runs."""

    session_id: str
    export_path: Path
    cwd: str
    command: tuple[str, ...]  # starts it interactively in ``cwd``
    started: bool = False  # True when a headless first turn was launched

    @property
    def resume(self) -> str:
        """The shell line that opens the combined session."""
        return f"cd {self.cwd} && claude --resume {self.session_id}"


# --------------------------------------------------------------------------- #
# Selecting conversations
# --------------------------------------------------------------------------- #
def rows(
    cwd: str | None,
    *,
    tag: str | None = None,
    query: str | None = None,
    subfolders: bool = True,
) -> list[ws.Row]:
    """The conversations of ``cwd`` (None: every directory), filtered by tag and query.

    ``query`` matches the title, label and first prompt without case.
    """
    only = ws.Filter(tags=(tag,)) if tag else ws.NO_FILTER
    out = ws.build_rows(cwd, only=only, subfolders=subfolders)
    if query:
        q = query.casefold()
        out = [
            r
            for r in out
            if q in r.display_title.casefold()
            or q in r.meta.label.casefold()
            or any(q in clean(s.first_prompt).casefold() for s in r.chain)
        ]
    return out


def select(
    cwd: str | None,
    *,
    ids: Iterable[str] = (),
    tag: str | None = None,
    subfolders: bool = True,
) -> list[ws.Row]:
    """The conversations named by ``ids`` (any id or 8-char prefix in a chain) or ``tag``.

    Raises:
        SessionsError: neither or both were given, or an id matches no conversation.
    """
    want = [i.strip() for i in ids if i.strip()]
    if bool(want) == bool(tag):
        raise SessionsError("give session ids or a tag, not both")
    found = rows(cwd, tag=tag, subfolders=subfolders)
    if not want:
        return found
    picked: list[ws.Row] = []
    for i in want:
        row = next((r for r in found if any(s.startswith(i) for s in r.ids)), None)
        if row is None:
            raise SessionsError(f"no session {i} here")
        if row not in picked:
            picked.append(row)
    return picked


# --------------------------------------------------------------------------- #
# Tags
# --------------------------------------------------------------------------- #
def tag(selected: list[ws.Row], add: Iterable[str] = (), remove: Iterable[str] = ()) -> int:
    """Add and remove tags on each conversation. Returns how many changed."""
    plus = [t.strip() for t in add if t.strip()]
    minus = {t.strip().casefold() for t in remove if t.strip()}
    changed = 0
    with ws.meta_locked():
        meta = ws.load_meta()
        for r in selected:
            old = meta.get(r.meta_key, ws.Meta())
            tags = [t for t in old.tags if t.casefold() not in minus]
            tags += [t for t in plus if t.casefold() not in {x.casefold() for x in tags}]
            if tuple(tags) != old.tags:
                meta[r.meta_key] = replace(old, tags=tuple(tags))
                changed += 1
        if changed:
            ws.save_meta(meta)
    return changed


# --------------------------------------------------------------------------- #
# Reading a transcript
# --------------------------------------------------------------------------- #
def clean(text: str) -> str:
    """User text without the blocks Claude Code injects; "" when nothing human is left."""
    text = _IMAGE_REF.sub("", _INJECTED_BLOCK.sub("", text)).strip()
    return "" if text.startswith(_INJECTED_START) else text


def turns(path: Path) -> list[Turn]:
    """The user and assistant text of one transcript, in order.

    Tool calls, tool results, subagent lines and injected text are left out. A
    malformed line is skipped; it does not stop the file.
    """
    out: list[Turn] = []
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return out
    for line in lines:
        try:
            d = json.loads(line)
        except ValueError:
            continue
        if not isinstance(d, dict) or d.get("isSidechain") or d.get("isMeta"):
            continue
        kind = d.get("type")
        msg = d.get("message")
        if kind not in ("user", "assistant") or not isinstance(msg, dict):
            continue
        text = ws._text_of(msg.get("content"))
        text = clean(text) if kind == "user" else text.strip()
        if text:
            out.append(Turn(str(kind), text, str(d.get("timestamp") or "")))
    return out


def first_text(row: ws.Row) -> str:
    """The first human prompt of a conversation, cut to ``FIRST_TEXT_CHARS``."""
    for s in row.chain:
        for t in turns(s.path):
            if t.role == "user":
                return t.text[:FIRST_TEXT_CHARS]
    return ""


def describe(row: ws.Row) -> dict[str, object]:
    """One conversation as plain data for a tool result."""
    return {
        "id": row.chain[0].session_id,
        "ids": list(row.ids),
        "title": row.display_title,
        "date": time.strftime("%Y-%m-%d %H:%M", time.localtime(row.mtime)),
        "tags": list(row.meta.tags),
        "cwd": row.cwd,
    }


# --------------------------------------------------------------------------- #
# Export, combine, trash
# --------------------------------------------------------------------------- #
def export_text(selected: list[ws.Row]) -> str:
    """Markdown of every selected conversation, oldest first: a header, then each turn."""
    parts: list[str] = []
    for r in sorted(selected, key=lambda r: r.chain[0].mtime):
        head = f"## {r.display_title}\n\n"
        head += f"- session: {', '.join(r.ids)}\n- cwd: {r.cwd}\n"
        if r.meta.tags:
            head += f"- tags: {', '.join(r.meta.tags)}\n"
        parts.append(head)
        for s in r.chain:
            for t in turns(s.path):
                who = "User" if t.role == "user" else "Claude"
                parts.append(f"### {who} ({t.timestamp[:16].replace('T', ' ')})\n\n{t.text}\n")
    return "\n".join(parts)


def exports_dir() -> Path:
    """Where exports go when no path is given."""
    return ws.data_dir() / "exports"


def export(
    selected: list[ws.Row],
    out: Path | None = None,
    *,
    roots: Iterable[Path] = (),
    force: bool = False,
) -> Path:
    """Write ``export_text`` to ``out`` (default: a new file in ``exports_dir``).

    Raises:
        SessionsError: nothing selected; ``out`` is relative, outside the data dir and
            ``roots``, or exists and ``force`` is not set.
    """
    if not selected:
        raise SessionsError("no sessions to export")
    if out is None:
        stamp = time.strftime("%Y%m%d-%H%M%S")
        out = exports_dir() / f"{stamp}-{selected[0].chain[0].session_id[:8]}-{len(selected)}.md"
    if not out.is_absolute():
        raise SessionsError(f"export path must be absolute: {out}")
    allowed = [ws.data_dir(), *roots]
    if not any(out.resolve().is_relative_to(Path(r).resolve()) for r in allowed):
        raise SessionsError(f"export path must be under the project or {ws.data_dir()}")
    if out.exists() and not force:
        raise SessionsError(f"{out} exists; pass force to overwrite")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"# Exported sessions\n\n{export_text(selected)}", encoding="utf-8")
    return out


def combine(selected: list[ws.Row], cwd: str, *, start: bool = False) -> Combined:
    """Export the conversations and prepare one new session seeded with that export.

    The sources are recorded as ``combined_from`` in the sidecar, with the union of
    their tags plus ``combined``. With ``start``, a headless first turn runs in ``cwd``
    (detached) so the transcript exists; otherwise ``Combined.command`` starts it.
    """
    if not selected:
        raise SessionsError("no sessions to combine")
    sid = str(uuid.uuid4())
    path = export(selected, exports_dir() / f"combined-{sid[:8]}.md")
    tags: list[str] = []
    for r in selected:
        tags += [t for t in r.meta.tags if t not in tags]
    if "combined" not in tags:
        tags.append("combined")
    ws.update_meta(
        sid,
        lambda m: replace(
            m, tags=tuple(tags), combined_from=tuple(i for r in selected for i in r.ids)
        ),
    )
    prompt = (
        f"Read {path}. It holds {len(selected)} earlier conversations, combined. "
        "Summarize what was decided and what is still open, then continue from there."
    )
    done = Combined(sid, path, cwd, ("claude", "--session-id", sid, prompt))
    if start:
        subprocess.Popen(
            ["claude", "-p", "--session-id", sid, prompt],
            cwd=cwd,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
            env={**os.environ, "CABILDO_COMBINED": "1"},
        )
        done = replace(done, started=True)
    return done


def _transcript_exists(session_id: str) -> bool:
    return any(ws.config_dir().joinpath("projects").glob(f"*/{session_id}.jsonl"))


def covered(selected: list[ws.Row]) -> bool:
    """True when a combined session that has started lists every id of ``selected``."""
    need = {i for r in selected for i in r.ids}
    return any(
        need <= set(m.combined_from) and _transcript_exists(sid)
        for sid, m in ws.load_meta().items()
        if m.combined_from
    )


def trash(selected: list[ws.Row], *, keep: str | None = None, force: bool = False) -> list[Path]:
    """Move the conversations to the workspace trash (reversible: RESTORE.txt).

    A combined session in the selection is left out: trashing by tag would
    otherwise pick it up with its sources.

    Raises:
        SessionsError: ``keep`` (the caller's own session) is selected, nothing is
            left, or no started combined session lists them and ``force`` is not set.
    """
    selected = [r for r in selected if not r.meta.combined_from]
    if not selected:
        raise SessionsError("no sessions to trash (combined sessions are never trashed here)")
    if keep and any(keep in r.ids for r in selected):
        raise SessionsError("refusing to trash the calling session")
    if not force and not covered(selected):
        raise SessionsError(
            "no started combined session lists these sessions: combine them and start it first"
        )
    return [ws.trash(r) for r in selected]
