"""Session operations behind the CLI and the sessions_* MCP tools (#44)."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from lines import PROJECT, ai_title, assistant, user

from cabildo import sessions_ops as ops
from cabildo.workspace import sessions
from conftest import Transcript


def _two(transcript: Transcript) -> None:
    transcript("aaaa1111", user("plan the trip"), assistant("Booked."), ai_title("Trip"), mtime=100)
    transcript("bbbb2222", user("fix the bug"), assistant("Fixed."), ai_title("Bug"), mtime=200)


def test_tag_then_list_by_tag(transcript: Transcript) -> None:
    _two(transcript)
    rows = ops.select(PROJECT, ids=["aaaa"])
    assert ops.tag(rows, add=["relationship", "trip"]) == 1
    assert ops.tag(rows, add=["Trip"]) == 0  # already there, case-insensitive
    found = ops.rows(PROJECT, tag="relationship")
    assert [r.chain[0].session_id for r in found] == ["aaaa1111"]
    ops.tag(found, remove=["trip"])
    assert ops.rows(PROJECT, tag="relationship")[0].meta.tags == ("relationship",)


def test_select_needs_ids_or_tag_and_rejects_unknown(transcript: Transcript) -> None:
    _two(transcript)
    with pytest.raises(ops.SessionsError):
        ops.select(PROJECT)
    with pytest.raises(ops.SessionsError):
        ops.select(PROJECT, ids=["aaaa"], tag="x")
    with pytest.raises(ops.SessionsError, match="no session zzzz"):
        ops.select(PROJECT, ids=["zzzz"])


def test_clean_cuts_injected_text() -> None:
    assert ops.clean("<system-reminder>x</system-reminder>hello") == "hello"
    assert ops.clean("<task-notification>done</task-notification>") == ""
    assert ops.clean("<bash-input>ls</bash-input><bash-stdout>a</bash-stdout>") == ""
    assert ops.clean("[Image #1] look at this") == "look at this"
    assert ops.clean("Caveat: The messages below were generated by the user while") == ""
    assert (
        ops.clean("<pasted_content>mine</pasted_content>")
        == "<pasted_content>mine</pasted_content>"
    )


def test_turns_skip_bad_lines_tools_and_sidechains(tmp_path: Path) -> None:
    path = tmp_path / "t.jsonl"
    lines = [
        json.dumps(user("<system-reminder>r</system-reminder>real question")),
        "{not json",
        json.dumps({**assistant("sub"), "isSidechain": True}),
        json.dumps({"type": "user", "message": {"content": [{"type": "tool_result"}]}}),
        json.dumps(
            {"type": "user", "message": {"content": [{"type": "text", "text": "block text"}]}}
        ),
        json.dumps(assistant("answer")),
    ]
    path.write_text("\n".join(lines))
    assert [(t.role, t.text) for t in ops.turns(path)] == [
        ("user", "real question"),
        ("user", "block text"),
        ("assistant", "answer"),
    ]


def test_contains_searches_all_text_and_conversation_reads_the_chain(
    transcript: Transcript,
) -> None:
    _two(transcript)
    assert [r.chain[0].session_id for r in ops.rows(PROJECT, contains="BOOKED")] == ["aaaa1111"]
    row = ops.select(PROJECT, ids=["aaaa"])[0]
    assert [(t.role, t.text) for t in ops.conversation(row)] == [
        ("user", "plan the trip"),
        ("assistant", "Booked."),
    ]


def test_create_records_made_from_and_trash_needs_it_started(
    transcript: Transcript, monkeypatch: pytest.MonkeyPatch
) -> None:
    launched: list[list[str]] = []
    monkeypatch.setattr(ops.subprocess, "Popen", lambda argv, **_kw: launched.append(argv))
    _two(transcript)
    rows = ops.select(PROJECT, ids=["aaaa", "bbbb"])
    ops.tag(rows, add=["old"])
    with pytest.raises(ops.SessionsError):
        ops.create(PROJECT, "  ")
    made = ops.create(
        PROJECT, "my notes", made_from=[i for r in rows for i in r.ids], tags=["old", "merged"]
    )
    assert launched == [["claude", "-p", "--session-id", made.session_id, "my notes"]]
    meta = sessions.load_meta()[made.session_id]
    assert set(meta.combined_from) == {"aaaa1111", "bbbb2222"}
    assert meta.tags == ("old", "merged")

    with pytest.raises(ops.SessionsError, match="sessions_create"):
        ops.trash(rows)  # its transcript does not exist yet

    transcript(made.session_id, user("my notes"), mtime=300)  # now it has started
    selected = ops.select(PROJECT, tag="old")  # also picks the new session
    assert len(selected) == 3
    with pytest.raises(ops.SessionsError, match="calling session"):
        ops.trash(selected, keep="aaaa1111")
    trashed = ops.trash(selected)
    assert len(trashed) == 2  # the new session is kept
    assert [r.chain[0].session_id for r in ops.rows(PROJECT)] == [made.session_id]
    assert all((d / "RESTORE.txt").exists() for d in trashed)
